/// TraverseV proof-of-work instance.
///
/// Construction fills a memory buffer using a fill adapted from Argon2d. Each
/// block is derived from its predecessor and a pseudorandomly selected earlier
/// block via Argon2's BLAKE2b-based compression function, repeated over
/// multiple passes.
///
/// Mining iteratively searches for a proof that satisfies this instance's
/// difficulty. Each candidate is evaluated by applying rounds of the
/// scryptROMix algorithm's second loop, mixing memory blocks into the
/// computation via Salsa20/8-based BlockMix.
#[cfg_attr(test, derive(Clone))]
pub struct TraverseV {
    mode: Mode,
    buffer: Vec<Block>,
    tag: [u8; 32],
    key: Option<[u8; 32]>,
    params: Params,
}

impl TraverseV {
    /// Build a new trustless `TraverseV` instance.
    ///
    /// Creates and fills a memory buffer, and stores this instance's
    /// application context and parameters.
    ///
    /// Proofs generated by this instance are trustless, meaning they are
    /// verifiable by any instance sharing the same application context and
    /// parameters.
    pub fn new_trustless(context: impl Into<String>, params: Params) -> Self {
        let context = context.into();
        let v = build_buffer(Mode::Trustless, None, &context, params);
        let mut tag = context_tag(&context);

        let this = Self {
            mode: Mode::Trustless,
            buffer: v,
            tag,
            key: None,
            params,
        };

        #[cfg(feature = "zeroize")]
        tag.zeroize();

        this
    }

    /// Build a new permissioned `TraverseV` instance.
    ///
    /// Creates and fills a memory buffer, and stores this instance's secret,
    /// application context, and parameters.
    ///
    /// Proofs generated by this instance are permissioned, meaning they are
    /// verifiable only by instances sharing the same application context,
    /// parameters, and shared secret.
    pub fn new_permissioned(
        secret: &[u8],
        context: impl Into<String>,
        params: Params,
    ) -> Self {
        let context = context.into();
        let v =
            build_buffer(Mode::Permissioned, Some(secret), &context, params);
        let mut tag = context_tag(&context);

        let mut hasher = Hasher::new_derive_key(&context);
        hasher.update(secret);
        let mut hash = hasher.finalize();
        let mut key: [u8; 32] = hash.into();

        let this = Self {
            mode: Mode::Permissioned,
            buffer: v,
            tag,
            key: Some(key),
            params,
        };

        #[cfg(feature = "zeroize")]
        {
            tag.zeroize();
            hasher.zeroize();
            hash.zeroize();
            key.zeroize();
        }

        this
    }

    /// Mine for a proof satisfying this instance's configured difficulty.
    ///
    /// Iteratively searches for candidates until one satisfies the difficulty.
    /// Runtime is unbounded on high difficulties. As the counter can overflow,
    /// the type must be wide enough to reach a satisfying proof, otherwise the
    /// counter wraps around causing an infinite loop.
    ///
    /// A [trustless](Self::new_trustless) instance mines for a trustless
    /// proof, and a [permissioned](Self::new_permissioned) instance mines for
    /// a permissioned proof.
    pub fn mine<T, N, I>(&self, input: &[u8], mut counter: T, increment: I) -> N
    where
        T: core::ops::AddAssign<I> + Into<N> + Copy,
        N: num_traits::ToBytes + Copy,
        I: Copy,
    {
        let mut hasher = Hasher::new();
        hasher.update(input);
        let mut hash = hasher.finalize();
        let mut prefix: [u8; 32] = hash.into();

        #[cfg(feature = "zeroize")]
        {
            hasher.zeroize();
            hash.zeroize();
        }

        let proof = loop {
            let v: N = counter.into();

            let mut candidate = self.evaluate(&prefix, v);
            let satisfied = self.check_n(&candidate);

            #[cfg(feature = "zeroize")]
            candidate.zeroize();

            // Break loop when the constraint is satisfied
            if bool::from(satisfied) {
                break v;
            }

            counter += increment
        };

        #[cfg(feature = "zeroize")]
        prefix.zeroize();

        proof
    }

    /// Verify that a proof satisfies this instance's difficulty.
    ///
    /// Successful verification requires the verifying instance's configuration
    /// to match the one the proof was mined with.
    ///
    /// A [trustless](Self::new_trustless) instance can only verify trustless
    /// proofs, and a [permissioned](Self::new_permissioned) instance can only
    /// verify permissioned proofs.
    pub fn verify<N: num_traits::ToBytes + Copy>(
        &self,
        input: &[u8],
        proof: N,
    ) -> bool {
        let mut hasher = Hasher::new();
        hasher.update(input);
        let mut hash = hasher.finalize();
        let mut prefix: [u8; 32] = hash.into();

        let mut candidate = self.evaluate(&prefix, proof);
        let satisfied = self.check_n(&candidate);

        #[cfg(feature = "zeroize")]
        {
            hasher.zeroize();
            hash.zeroize();
            prefix.zeroize();
            candidate.zeroize();
        }

        bool::from(satisfied)
    }

    /// This `TraverseV` instance's mode, as either trustless or permissioned.
    pub const fn mode(&self) -> Mode {
        self.mode
    }

    fn evaluate<N: num_traits::ToBytes + Copy>(
        &self,
        prefix: &[u8; 32],
        v: N,
    ) -> [u8; 32] {
        let mut hasher = if let Some(key) = &self.key {
            Hasher::new_keyed(key)
        } else {
            Hasher::new()
        };
        hasher.update(prefix);
        hasher.update(v.to_le_bytes().as_ref());
        hasher.update(&self.tag);

        let mut bytes = [0u8; Block::SIZE];
        let mut reader = hasher.finalize_xof();
        reader.fill(&mut bytes);
        let mut x = Block::new();
        x.copy_from_bytes(&bytes);

        let k = self.params.e_cost() as usize;
        iter_mix(&mut x, &self.buffer, k);
        let mut x_bytes = [0u8; Block::SIZE];
        x.copy_to_bytes(&mut x_bytes);
        let mut hash = blake3::hash(&x_bytes);
        let candidate: [u8; 32] = hash.into();

        #[cfg(feature = "zeroize")]
        {
            hasher.zeroize();
            reader.zeroize();
            bytes.zeroize();
            x.zeroize();
            x_bytes.zeroize();
            hash.zeroize();
        }

        candidate
    }

    fn check_n(&self, candidate: &[u8; 32]) -> Choice {
        let n = self.params.n_cost() as u8;
        let bytes = (n / 8) as usize;
        let bits = n % 8;

        // Verify first N bytes are zero, following N bits are zero
        let mut satisfied = Choice::from(1u8);
        for byte in &candidate[..bytes] {
            satisfied &= byte.ct_eq(&0u8);
        }
        if bits > 0 {
            let mask = (0xFF << (8 - bits)) as u8;
            satisfied &= (candidate[bytes] & mask).ct_eq(&0u8);
        }

        satisfied
    }
}

fn context_tag(context: &str) -> [u8; 32] {
    let mut hasher = Hasher::new();
    hasher.update(context.as_bytes());
    let mut hash = hasher.finalize();
    let tag: [u8; 32] = hash.into();

    #[cfg(feature = "zeroize")]
    {
        hasher.zeroize();
        hash.zeroize();
    }

    tag
}

impl core::fmt::Debug for TraverseV {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("TraverseV")
            .field("mode", &self.mode)
            .field("params", &self.params)
            .finish_non_exhaustive()
    }
}

#[cfg(feature = "zeroize")]
impl Drop for TraverseV {
    fn drop(&mut self) {
        self.tag.zeroize();
        self.key.zeroize();
    }
}

#[cfg(feature = "zeroize")]
impl ZeroizeOnDrop for TraverseV {}

#[cfg(test)]
mod tests {
    use super::*;

    const CONTEXT: &str = "TRAVERSEV_TEST";
    const SECRET: &[u8] = b"This is a secret.";
    const INPUT: &[u8] = b"Some mining input.";

    /// Parameters for testing.
    ///
    /// 8 KiB memory, 2 memory fill iterations, 2 evaluation mixing rounds,
    /// and a difficulty of 12.
    fn params() -> Params {
        Params::new(8, 2, 2, 12).expect("test parameters are valid")
    }

    #[test]
    fn trustless_proof_verifies() {
        let miner = TraverseV::new_trustless(CONTEXT, params());
        let verifier = miner.clone();

        let proof: u128 = miner.mine(INPUT, 0u128, 1);
        assert!(verifier.verify(INPUT, proof));
    }

    #[test]
    fn permissioned_proof_verifies() {
        let miner = TraverseV::new_permissioned(SECRET, CONTEXT, params());
        let verifier = miner.clone();

        let proof: u128 = miner.mine(INPUT, 0u128, 1);
        assert!(verifier.verify(INPUT, proof));
    }

    #[test]
    fn trustless_rejects_permissioned_proof() {
        // At n = 12 a wrong instance accepts a proof with probability 1/4096.
        let miner = TraverseV::new_permissioned(SECRET, CONTEXT, params());
        let verifier = TraverseV::new_trustless(CONTEXT, params());

        assert_eq!(miner.mode(), Mode::Permissioned);
        assert_eq!(verifier.mode(), Mode::Trustless);

        let proof: u128 = miner.mine(INPUT, 0u128, 1);
        assert!(!verifier.verify(INPUT, proof));
    }

    #[test]
    fn verify_rejects_unsatisfied_difficulty() {
        let params = Params::new(2 * 1024, 2, 2, 255)
            .expect("test parameters are valid");

        let verifier = TraverseV::new_trustless(CONTEXT, params);
        assert!(!verifier.verify(INPUT, 0u128));
    }

    #[test]
    fn debug_omits_secret_state() {
        let params = params();
        let tv = TraverseV::new_permissioned(SECRET, CONTEXT, params);

        let output = format!("{tv:?}");

        assert!(output.contains("TraverseV"));
        assert!(output.contains(&format!("{:?}", tv.mode())));
        assert!(output.contains(&format!("{params:?}")));

        // No sensitive fields should appear
        for field in ["buffer", "tag", "key"] {
            assert!(!output.contains(field));
        }
    }
}
